"""Deterministic topic-fact generator for the plastic-graph activation test.

Produces 10 topics * 100 facts = 1000 total facts. Each topic is a distinct
semantic domain (Python preferences, running shoes, coffee...) so a graph
that learns from focused queries on one topic should cluster nodes within
that topic.

Each fact is a short declarative sentence with an ATTR-VALUE pattern so
questions can be generated by masking the VALUE (e.g. "what's my preferred
Python formatter?" -> "black").

Design choices:
- Deterministic (seeded), so runs are reproducible.
- Attributes chosen to have specific-term answers (for F1/EM scoring).
- 20 attributes x 5 values each = 100 facts per topic.
- Ensures no overlap between topics (e.g., no "my favorite" fact shared).
"""

from __future__ import annotations

import random
from dataclasses import dataclass


@dataclass
class Fact:
    topic: str
    attribute: str
    value: str

    @property
    def text(self) -> str:
        """Render fact as declarative statement."""
        return f"My preferred {self.attribute} is {self.value}."

    @property
    def question(self) -> str:
        """Question that should retrieve this fact as gold."""
        return f"What is my preferred {self.attribute}?"

    @property
    def answer(self) -> str:
        return self.value


