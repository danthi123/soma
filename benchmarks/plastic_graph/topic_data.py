def generate_facts(seed: int = 42) -> list[Fact]:
    """Generate 1000 facts (100 per topic) deterministically.

    For each (attribute, values) tuple, we pick the FIRST value as the
    "chosen" one (the user's preference). We then also generate 4 more
    paraphrase statements around that chosen value.

    Pattern: 5 paraphrase statements per attribute x 20 attributes =
    100 facts per topic.
    """
    rng = random.Random(seed)
    facts: list[Fact] = []
    for topic_name, attrs in TOPICS:
        assert len(attrs) == 20, (
            f"topic {topic_name} has {len(attrs)} attrs, expected 20"
        )
        for attr_name, values in attrs:
            assert len(values) == 5, (
                f"attr {attr_name} has {len(values)} values, expected 5"
            )
            chosen = values[0]
            templates = [
                f"My preferred {attr_name} is {chosen}.",
                f"I prefer {chosen} for {attr_name}.",
                f"When choosing {attr_name}, I go with {chosen}.",
                f"For {attr_name}, {chosen} is my go-to.",
                f"I stick with {chosen} for {attr_name}.",
            ]
            for tmpl in templates:
                f = Fact(topic=topic_name, attribute=attr_name, value=chosen)
                f.__dict__["_text_override"] = tmpl
                facts.append(f)
    rng.shuffle(facts)
    return facts


def get_fact_text(fact: Fact) -> str:
    """Text rendering, respecting any template override."""
    return fact.__dict__.get("_text_override", fact.text)


def generate_questions(
    facts: list[Fact], per_topic: int = 20, seed: int = 42,
) -> dict[str, list[Fact]]:
    """Generate up to `per_topic` sample questions per topic.

    Returns a dict topic_name -> list of Facts. Each fact carries its
    own canonical `.question`/`.answer`. Within a topic we dedupe by
    attribute so each question targets a unique attribute.
    """
    rng = random.Random(seed)
    by_topic: dict[str, dict[str, Fact]] = {}
    for f in facts:
        by_topic.setdefault(f.topic, {}).setdefault(f.attribute, f)

    out: dict[str, list[Fact]] = {}
    for topic, attr_map in by_topic.items():
        unique = list(attr_map.values())
        rng.shuffle(unique)
        out[topic] = unique[:per_topic]
    return out


