"""Benchmark MemoryLayer at scale: 1K, 10K, 100K entries.

Validates FAISS auto-switch, measures store/retrieve latency curves,
and disk footprint growth.

    python scripts/benchmark_scale.py --out reports/scale-benchmark.md

Uses a synthetic dataset of templated sentences. Does NOT require
sentence-transformers (uses SOMA's TextEncoder for speed at scale).
"""

from __future__ import annotations

import argparse
import tempfile
import time
from pathlib import Path
from typing import Any

import torch

from soma.io.text_encoder import TextEncoder, train_bpe_tokenizer
from soma.memory import MemoryLayer

SCALE_TIERS = [100, 1_000, 10_000, 100_000]
QUERY_COUNT = 50
K = 5

TEMPLATES = [
    "User {} lives in city {} and works at company {}",
    "The project deadline for team {} is {} days from now",
    "User {} prefers {} and uses {} for coding",
    "Meeting note: {} discussed {} with {} on topic {}",
    "Reminder for {}: buy {} at {} before {}",
]


def _generate_entries(n: int) -> list[str]:
    entries = []
    for i in range(n):
        t = TEMPLATES[i % len(TEMPLATES)]
        words = [f"w{(i * 7 + j) % 997}" for j in range(t.count("{}"))]
        entries.append(t.format(*words))
    return entries


def _generate_queries(n: int) -> list[str]:
    return [f"tell me about w{i * 13 % 997}" for i in range(n)]


def _benchmark_tier(
    n: int,
    tokenizer: Any,
    encoder: TextEncoder,
    queries: list[str],
    tmp: Path,
) -> dict[str, Any]:
    torch.manual_seed(42)
    entries = _generate_entries(n)

    mem = MemoryLayer(
        tokenizer=tokenizer,
        encoder=encoder,
        faiss_threshold=10_000,
    )

    t0 = time.perf_counter()
    for text in entries:
        mem.store(text)
    store_total = time.perf_counter() - t0

    using_faiss = mem._faiss_index is not None

    retrieve_times = []
    for q in queries:
        t1 = time.perf_counter()
        mem.retrieve(q, k=K)
        retrieve_times.append(time.perf_counter() - t1)

    bundle_path = tmp / f"scale-{n}"
    mem.save(bundle_path)
    disk_bytes = sum(f.stat().st_size for f in bundle_path.rglob("*") if f.is_file())

    return {
        "n": n,
        "store_total_s": store_total,
        "store_per_op_ms": store_total * 1000 / n,
        "retrieve_avg_ms": sum(retrieve_times) * 1000 / len(retrieve_times),
        "retrieve_p99_ms": sorted(retrieve_times)[-max(1, len(retrieve_times) // 100)] * 1000,
        "disk_mb": disk_bytes / (1024 * 1024),
        "using_faiss": using_faiss,
    }


def _format_report(results: list[dict[str, Any]]) -> str:
    lines = [
        "# MemoryLayer Scale Benchmark",
        "",
        f"**Queries:** {QUERY_COUNT} random queries, k={K}.",
        "**Embedding:** SOMA TextEncoder (32-d, random init) for speed.",
        "**FAISS threshold:** 10,000 entries (auto-switch).",
        "",
        "| Entries | Store (ms/op) | Retrieve avg (ms) | Retrieve p99 (ms)"
        " | Disk (MB) | FAISS? |",
        "| ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in results:
        lines.append(
            f"| {r['n']:,} | {r['store_per_op_ms']:.3f} "
            f"| {r['retrieve_avg_ms']:.3f} "
            f"| {r['retrieve_p99_ms']:.3f} "
            f"| {r['disk_mb']:.2f} "
            f"| {'yes' if r['using_faiss'] else 'no'} |"
        )
    lines += [
        "",
        "## Observations",
        "",
        "- Below 10K: linear scan, sub-millisecond retrieves.",
        "- At/above 10K: FAISS IndexFlatIP activates automatically.",
        "- Disk footprint scales linearly (JSON index + embedding tensor).",
        "",
        "---",
        "",
        "Generated by `scripts/benchmark_scale.py`.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--out",
        type=Path,
        default=Path("reports/scale-benchmark.md"),
    )
    p.add_argument(
        "--tiers",
        type=int,
        nargs="+",
        default=SCALE_TIERS,
    )
    args = p.parse_args()

    corpus = _generate_entries(1000)
    tokenizer = train_bpe_tokenizer(corpus, vocab_size=512)
    encoder = TextEncoder(tokenizer, embed_dim=32, max_seq_len=64)
    queries = _generate_queries(QUERY_COUNT)

    results: list[dict[str, Any]] = []
    tmp = Path(tempfile.mkdtemp())
    try:
        for n in args.tiers:
            print(f"Benchmarking N={n:,}...")
            r = _benchmark_tier(n, tokenizer, encoder, queries, tmp)
            print(
                f"  store={r['store_per_op_ms']:.3f}ms/op  "
                f"retrieve={r['retrieve_avg_ms']:.3f}ms  "
                f"disk={r['disk_mb']:.2f}MB  "
                f"faiss={'yes' if r['using_faiss'] else 'no'}"
            )
            results.append(r)
    finally:
        import shutil

        shutil.rmtree(tmp, ignore_errors=True)

    report = _format_report(results)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"\nReport: {args.out}")


if __name__ == "__main__":
    main()
